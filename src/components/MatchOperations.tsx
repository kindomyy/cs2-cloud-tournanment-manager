import { useState } from "react";
import { useArena, ApiError } from "../arena/ArenaContext";
import { operation } from "../arena/operationsApi";
import type { Match } from "../data";
import { useI18n } from "../i18n";

export function MatchOperations({
  match,
  disabled = false,
  onChange,
}: {
  match: Match;
  disabled?: boolean;
  onChange?: () => void | Promise<void>;
}) {
  const arena = useArena();
  const { lang, tx, errText } = useI18n();
  const [busy, setBusy] = useState(false),
    [error, setError] = useState(""),
    [notice, setNotice] = useState(""),
    [pending, setPending] = useState<{
      data: Record<string, unknown>;
      message: string;
    } | null>(null),
    [stopped, setStopped] = useState(false),
    [round, setRound] = useState(0),
    [mapNumber, setMapNumber] = useState(0),
    [winner, setWinner] = useState(match.a || ""),
    [note, setNote] = useState(""),
    [keepVeto, setKeepVeto] = useState(true);
  const duel = match.id.startsWith("duel-");
  async function run(data: Record<string, unknown>) {
    if (disabled || arena.snapshot.me?.role !== "admin") return;
    setBusy(true);
    setError("");
    setNotice("");
    try {
      const result = await operation({
        matchId: match.id,
        revision: arena.snapshot.revision,
        ...data,
      });
      setPending(null);
      setStopped(false);
      setNotice(
        result.message
          ? errText(result.message)
          : tx("İşlem uygulandı.", "Action applied."),
      );
      await arena.refresh();
      await onChange?.();
    } catch (e) {
      setError(errText((e as Error).message));
      if (e instanceof ApiError && e.data.requiresConfirm) {
        setPending({
          data: { revision: arena.snapshot.revision, ...data },
          message: errText(e.message),
        });
        setStopped(false);
        setError("");
      }
    } finally {
      setBusy(false);
    }
  }
  const off = disabled || busy || !arena.online;
  if (arena.snapshot.me?.role !== "admin" && !(!arena.online && arena.previewAdmin)) return null;
  return (
    <div className="match-operations admin-settings-card">
      <span className="eyebrow">
        {tx("MAÇ", "MATCH")} / {duel ? tx("ÖZEL 1V1", "CUSTOM 1V1") : match.id}
      </span>
      <h3>{tx("Sunucu ve maç kontrolü", "Server and match controls")}</h3>
      <p>
        {lang === "en" ? (
          <>
            Loading sends the match config directly to the server. After marking
            ready on the site, players must still type <strong>.ready</strong>{" "}
            in-game.
          </>
        ) : (
          <>
            Yükleme, maç dosyasını doğrudan sunucuya iletir. Sitedeki hazır
            işaretinden sonra oyuncular oyun içinde ayrıca{" "}
            <strong>.ready</strong> yazmalı.
          </>
        )}
      </p>
      {disabled && (
        <p className="draft-indicator">
          {tx("Önce taslak değişikliklerini kaydet.", "Save draft changes first.")}
        </p>
      )}
      <div className="operation-buttons">
        {(
          [
            ["load", tx("Maçı sunucuya yükle", "Load match on server")],
            ["pause", tx("Duraklat", "Pause")],
            ["unpause", tx("Devam et", "Unpause")],
            ["end", tx("Sunucudaki maçı bitir", "End match on server")],
          ] as const
        ).map(([command, label]) => (
          <button
            className={command === "load" ? "button-primary" : "button-text"}
            key={command}
            disabled={off}
            onClick={() => void run({ action: "server", command })}
          >
            {label}
          </button>
        ))}
      </div>
      <details>
        <summary>{tx("Kurtarma işlemleri", "Recovery actions")}</summary>
        <p>
          {tx(
            "MatchZy’nin mevcut maç için oluşturduğu raund backup’ı kullanılır. Harita değişmez; güncel haritanın backup numarasını gir.",
            "Uses the round backup generated by MatchZy for the current match. The map does not change; enter the backup number for the active map.",
          )}
        </p>
        <div className="admin-fields">
          <label>
            {tx("Sunucudaki backup raundu", "Server backup round")}
            <input
              type="number"
              min={0}
              max={100}
              value={round}
              onChange={(e) => setRound(Number(e.target.value))}
            />
          </label>
          <label>
            {tx("BO3 harita sırası", "BO3 map index")}
            <select
              value={mapNumber}
              onChange={(e) => setMapNumber(Number(e.target.value))}
            >
              {Array.from(
                { length: match.format === "BO1" ? 1 : 3 },
                (_, i) => (
                  <option key={i} value={i}>
                    {tx(`${i + 1}. harita`, `Map ${i + 1}`)}
                  </option>
                ),
              )}
            </select>
          </label>
        </div>
        <button
          className="button-text"
          disabled={off}
          onClick={() =>
            void run({ action: "server", command: "restore", round })
          }
        >
          {tx("Sunucuda backup yükle", "Restore backup on server")}
        </button>
        {!duel && (
          <>
            <p>
              {tx(
                `Sunucuda backup yüklenmiş ama olay siteye ulaşmamışsa, aşağıdan yalnızca sitenin beklediği raundu düzelt. 0, ilk raundun öncesidir; sonraki skor toplamı ${round + 1} olmalı.`,
                `If a backup was restored on the server without reaching the site, adjust only the site’s expected round below. 0 is before the first round; the next score total must be ${round + 1}.`,
              )}
            </p>
            <button
              className="button-text"
              disabled={off}
              onClick={() => void run({ action: "resync", round, mapNumber })}
            >
              {tx("Siteyi backup durumuna eşitle", "Sync site to backup state")}
            </button>
            <label className="settings-checkbox">
              <input
                type="checkbox"
                checked={keepVeto}
                onChange={(e) => setKeepVeto(e.target.checked)}
              />
              {tx("Tekrarda mevcut vetoyu koru", "Keep existing veto on replay")}
            </label>
            <button
              className="button-text"
              disabled={off}
              onClick={() => void run({ action: "replay", keepVeto })}
            >
              {tx("Yeni kimlikle tekrar oynat", "Replay with new match ID")}
            </button>
            <button
              className="button-text"
              disabled={off}
              onClick={() => void run({ action: "refresh-lineup" })}
            >
              {tx("Seçili maçın kadrosunu yenile", "Refresh match lineup")}
            </button>
          </>
        )}
      </details>
      {!duel && match.a && match.b && (
        <details>
          <summary>{tx("Hükmen sonuç", "Forfeit result")}</summary>
          <p>
            {tx(
              "BO1 için 13–0, BO3 için 2–0 olarak işaretlenir. Oyuncu istatistiği oluşturulmaz.",
              "Recorded as 13–0 for BO1 and 2–0 for BO3. No player stats are generated.",
            )}
          </p>
          <label>
            {tx("Kazanan", "Winner")}
            <select
              value={[match.a, match.b].includes(winner) ? winner : match.a}
              onChange={(e) => setWinner(e.target.value)}
            >
              {[match.a, match.b].map((id) => (
                <option key={id} value={id}>
                  {arena.snapshot.config.teams.find((t) => t.id === id)?.name ||
                    id}
                </option>
              ))}
            </select>
          </label>
          <label>
            {tx("Karar nedeni", "Decision reason")}
            <textarea
              maxLength={300}
              value={note}
              onChange={(e) => setNote(e.target.value)}
            />
          </label>
          <button
            className="button-text danger-text"
            disabled={off || !note.trim()}
            onClick={() =>
              void run({
                action: "forfeit",
                winner: [match.a, match.b].includes(winner) ? winner : match.a,
                note,
              })
            }
          >
            {tx("Hükmen sonucu kaydet", "Record forfeit result")}
          </button>
        </details>
      )}
      {pending && (
        <div className="change-confirm" role="alert">
          <h3>{tx("İşlemi gözden geçir", "Review action")}</h3>
          <p>{pending.message}</p>
          {["replay"].includes(String(pending.data.action)) && (
            <label className="settings-checkbox">
              <input
                type="checkbox"
                checked={stopped}
                onChange={(e) => setStopped(e.target.checked)}
              />
              {tx(
                "Sunucudaki mevcut maçı durdurdum.",
                "I stopped the current match on the server.",
              )}
            </label>
          )}
          <button
            className="button-primary"
            disabled={busy || (pending.data.action === "replay" && !stopped)}
            onClick={() =>
              void run({
                ...pending.data,
                confirm: true,
                serverStoppedConfirmed: stopped,
              })
            }
          >
            {tx("Onayla ve uygula", "Confirm and apply")}
          </button>
          <button className="button-text" onClick={() => setPending(null)}>
            {tx("Vazgeç", "Cancel")}
          </button>
        </div>
      )}
      {error && (
        <p className="form-error" role="alert">
          {error}
        </p>
      )}
      {notice && (
        <p className="save-notice" role="status">
          {notice}
        </p>
      )}
    </div>
  );
}
